// Helper function to get icon by name
export function getIconByName(name: string | null | undefined) {
  if (!name) return null;
  const icon = DFS_POOL_ICONS.find(i => i.name === name);
  return icon ? icon.component : null;
}

// Get all categories
export function getIconCategories(): string[] {
  const categories = new Set(DFS_POOL_ICONS.map(icon => icon.category));
  return Array.from(categories).sort();
}

// Get icons by category
export function getIconsByCategory(category: string): IconDefinition[] {
  return DFS_POOL_ICONS.filter(icon => icon.category === category);
}

// Search icons by label
export function searchIcons(query: string): IconDefinition[] {
  const lowerQuery = query.toLowerCase();
  return DFS_POOL_ICONS.filter(icon => 
    icon.label.toLowerCase().includes(lowerQuery) ||
    icon.name.toLowerCase().includes(lowerQuery) ||
    icon.category.toLowerCase().includes(lowerQuery)
  );
}


